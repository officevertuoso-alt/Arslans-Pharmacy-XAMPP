// Create/refresh .htaccess to block direct web access
$htaccess_path = BACKUP_DIR . '.htaccess';
$htaccess_content = "# Auto-generated by Pharmacy Backup Module — DO NOT DELETE\n"
    . "Require all denied\n"    // Apache 2.4+
    . "Order deny,allow\n"      // Apache 2.2 fallback
    . "Deny from all\n";

if (!file_exists($htaccess_path) || file_get_contents($htaccess_path) !== $htaccess_content) {
    file_put_contents($htaccess_path, $htaccess_content);
}

// ── Read existing backup files ────────────────────────────────────────────────
$backup_files = [];

if (is_dir(BACKUP_DIR)) {
    $iterator = new DirectoryIterator(BACKUP_DIR);
    foreach ($iterator as $file) {
        // Only accept .sql and .sql.gz files
        if ($file->isDot() || $file->isDir()) continue;

        $fname = $file->getFilename();
        $ext   = pathinfo($fname, PATHINFO_EXTENSION);

        // Accept .gz (for .sql.gz) and .sql
        if (!in_array($ext, ['sql', 'gz'], true)) continue;
        if ($ext === 'gz' && !str_ends_with($fname, '.sql.gz')) continue;

        $backup_files[] = [
            'filename'   => $fname,
            'size'       => $file->getSize(),
            'size_human' => formatFileSize($file->getSize()),
            'created_at' => $file->getMTime(),
            'created_fmt'=> date('d-M-Y H:i:s', $file->getMTime()),
            'is_gzip'    => str_ends_with($fname, '.sql.gz'),
        ];
    }

    // Sort newest first
    usort($backup_files, fn($a, $b) => $b['created_at'] - $a['created_at']);
    $backup_files = array_slice($backup_files, 0, BACKUP_MAX_DISPLAY);
}

