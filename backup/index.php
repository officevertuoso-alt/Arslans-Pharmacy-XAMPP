<script>
(function () {
    'use strict';

    const CSRF_TOKEN  = <?= json_encode($csrf_token) ?>;
    const overlay     = document.getElementById('loadingOverlay');
    const loadingMsg  = document.getElementById('loadingMsg');

    // ── Create Backup ────────────────────────────────────────────────────────
    document.getElementById('btnCreateBackup').addEventListener('click', function () {
        if (!confirm('Create a new database backup now?')) return;

        overlay.classList.add('show');
        loadingMsg.textContent = 'Creating backup, please wait…';

        fetch('../ajax/backup_database.php', {
            method : 'POST',
            headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
            body   : 'csrf_token=' + encodeURIComponent(CSRF_TOKEN),
        })
        .then(r => r.json())
        .then(data => {
            overlay.classList.remove('show');
            if (data.success) {
                showAlert('success',
                    '✅ Backup created: <strong>' + escHtml(data.filename) + '</strong> ' +
                    '(' + escHtml(data.size) + ')');
                // Reload after short delay so new file appears
                setTimeout(() => location.reload(), 1800);
            } else {
                showAlert('danger', '❌ ' + escHtml(data.message || 'Backup failed.'));
            }
        })
        .catch(() => {
            overlay.classList.remove('show');
            showAlert('danger', '❌ Network error. Could not reach backup endpoint.');
        });
    });

    // ── Delete ───────────────────────────────────────────────────────────────
    let fileToDelete = null;
    const deleteModal = new bootstrap.Modal(document.getElementById('deleteModal'));

    document.querySelectorAll('.btn-delete').forEach(btn => {
        btn.addEventListener('click', function () {
            fileToDelete = this.dataset.filename;
            document.getElementById('deleteFilename').textContent = fileToDelete;
            deleteModal.show();
        });
    });

    document.getElementById('confirmDelete').addEventListener('click', function () {
        if (!fileToDelete) return;
        this.disabled = true;
        this.innerHTML = '<span class="spinner-border spinner-border-sm me-1"></span>Deleting…';

        fetch('../ajax/delete_backup.php', {
            method : 'POST',
            headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
            body   : 'csrf_token=' + encodeURIComponent(CSRF_TOKEN)
                   + '&filename='  + encodeURIComponent(fileToDelete),
        })
        .then(r => r.json())
        .then(data => {
            deleteModal.hide();
            if (data.success) {
                showAlert('success', '✅ Backup deleted: ' + escHtml(fileToDelete));
                setTimeout(() => location.reload(), 1200);
            } else {
                showAlert('danger', '❌ ' + escHtml(data.message || 'Delete failed.'));
            }
        })
        .catch(() => {
            deleteModal.hide();
            showAlert('danger', '❌ Network error.');
        });
    });

    // ── Restore redirect ─────────────────────────────────────────────────────
    const restoreModal = new bootstrap.Modal(document.getElementById('restoreRedirectModal'));
    const btnGoRestore = document.getElementById('btnGoRestore');

    document.querySelectorAll('.btn-restore').forEach(btn => {
        btn.addEventListener('click', function () {
            const fname = this.dataset.filename;
            document.getElementById('restoreFilename').textContent = fname;
            btnGoRestore.href = 'restore.php?prefill=' + encodeURIComponent(fname);
            restoreModal.show();
        });
    });

    // ── Helpers ──────────────────────────────────────────────────────────────
    function showAlert(type, html) {
        const div = document.createElement('div');
        div.className = 'alert alert-' + type + ' alert-dismissible fade show mt-3';
        div.setAttribute('role', 'alert');
        div.innerHTML = html + '<button type="button" class="btn-close" data-bs-dismiss="alert"></button>';
        document.querySelector('.container-fluid').prepend(div);
        window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    function escHtml(str) {
        const d = document.createElement('div');
        d.appendChild(document.createTextNode(String(str)));
        return d.innerHTML;
    }
})();
</script>

